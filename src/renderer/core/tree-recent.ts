/**
 * Недавно изменённые файлы: свежая правка видна в дереве.
 *
 * В дереве файлов правят обычно те несколько, над которыми работаешь сейчас, а между
 * ними — десятки чужих. Git-пометки говорят о правках с последнего коммита, но не о
 * ВРЕМЕНИ: файл, тронутый неделю назад и не закоммиченный, помечен так же, как
 * сохранённый минуту назад. Отметка свежести это разделяет.
 *
 * Логика чистая: время правки даёт диск (`DirEntry.mtimeMs`), «сейчас» приходит
 * аргументом — поэтому поведение видно в тестах, без часов и без дерева.
 *
 * Окно свежести — сутки по умолчанию. Это не «горячие файлы» редактора (у нас такого
 * списка нет), а «тронуто недавно»: за сутки успеваешь и отвлечься, и вернуться, а
 * недельная отметка стояла бы почти на всём.
 */

/** Час в миллисекундах — единица, от которой считаются окна. */
const HOUR_MS = 60 * 60 * 1000;

/** Окно свежести по умолчанию: сутки. */
export const RECENT_WINDOW_MS = 24 * HOUR_MS;

/**
 * Тронут ли файл недавно. `now` — текущее время (мс), `windowMs` — окно свежести.
 *
 * Будущее время трактуем как «свежее»: часы на разных машинах и в разных файловых
 * системах расходятся, и файл с временем «через минуту» — это не ошибка того, кто его
 * только что записал. А вот `0` (время неизвестно) свежим не считаем: иначе пометили
 * бы полдерева там, где время не сообщили.
 */
export function isRecentlyModified(mtimeMs: number, now: number, windowMs = RECENT_WINDOW_MS): boolean {
  if (!Number.isFinite(mtimeMs) || mtimeMs <= 0) return false;
  if (!Number.isFinite(windowMs) || windowMs <= 0) return false;
  return now - mtimeMs <= windowMs;
}

/**
 * Подпись «когда тронут» — человеческим языком, а не отметкой времени: в дереве важна
 * свежесть, а не точное время. Пусто для времени неизвестного.
 */
export function recentLabel(mtimeMs: number, now: number): string {
  if (!Number.isFinite(mtimeMs) || mtimeMs <= 0) return '';
  const diff = now - mtimeMs;
  // Часы разошлись: правка «в будущем» — говорим «только что», а не «через час».
  if (diff < 0) return 'только что';
  if (diff < 60 * 1000) return 'только что';
  if (diff < HOUR_MS) return `${Math.floor(diff / (60 * 1000))} мин назад`;
  if (diff < RECENT_WINDOW_MS) return `${Math.floor(diff / HOUR_MS)} ч назад`;
  const days = Math.floor(diff / RECENT_WINDOW_MS);
  return days === 1 ? 'вчера' : `${days} дн назад`;
}
