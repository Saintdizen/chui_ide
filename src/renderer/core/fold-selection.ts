/**
 * Свёртка региона выбора — арифметика, без DOM и без LSP.
 *
 * Зачем: свёртка умела сворачивать блок целиком (`foldAt` — блок под кареткой) и
 * весь файл по уровню, но не «вот этот кусок, который я выделил». В VS Code это
 * `Ctrl+K Ctrl+[`: выделил тело функции — и оно сложилось, даже если язык не
 * прислал для него `foldingRange`.
 *
 * Почему отдельный модуль. Правка выглядит простой, но у неё есть три неочевидных
 * правила, каждое из которых портит результат, если о нём забыть:
 *
 *  1. Границы выделения ВНЕШНИЕ: если каретка стоит в начале строки 10, строку 10
 *     человек читает как свою — её нельзя схлопывать.
 *  2. Одна строка — не регион. Свернуть строку «в себя» значит спрятать её целиком,
 *     и на экране не останется ничего.
 *  3. Такой регион не должен наезжать на уже известный блок. Иначе в списке
 *     окажутся два диапазона с общими строками, и скрытие посчитает их дважды —
 *     арифметика `hiddenBefore` на пересечениях врёт.
 */

import type { FoldRange } from '../../shared/fold-ranges';

/**
 * Регион свёртки ровно по выделению.
 *
 * `null` — сворачивать нечего: пустое выделение, одна строка, или регион уже
 * известен языку (тогда честнее пользоваться им: у него правильные границы).
 *
 * `anchor`/`head` — позиции мыши в любом порядке: человек ведёт выделение и вниз,
 * и вверх, и «начало» здесь — минимум, а не то, что пришло первым.
 */
export function selectionRegion(
  anchorLine: number,
  headLine: number,
  known: readonly FoldRange[] = [],
): FoldRange | null {
  const from = Math.min(anchorLine, headLine);
  const to = Math.max(anchorLine, headLine);
  // Одна строка (и меньше) — это не регион: скрывать нечего, а строка исчезнет.
  if (to <= from) return null;
  // Уже есть блок с такими же границами — не плодим двойник: у него та же строка
  // начала, и значок в жёлобе сработал бы по нему, а не по нашему.
  if (known.some((range) => range.startLine === from && range.endLine === to)) return null;
  return { startLine: from, endLine: to };
}

/**
 * Сколько строк спрятал ЭТОТ схлопнутый блок.
 *
 * Считаются не все строки диапазона: строка начала остаётся видимой — она и есть
 * заголовок со значком. Поэтому `endLine - startLine`, а не `+1`.
 */
export function hiddenLineCount(range: FoldRange): number {
  return Math.max(0, range.endLine - range.startLine);
}

/**
 * Подпись для заголовка схлопнутого блока: «⋯ 12 строк».
 *
 * Зачем: схлопнутый блок рисуется одной строкой, и без числа человек не понимает,
 * что именно он не читает — одну строку или двести.
 *
 * Правильные формы нужны по-русски: «1 строка», «2 строки», «5 строк», «11 строк»
 * (не «строка» — одиннадцать, но не двадцать один).
 */
export function foldLabel(hidden: number): string {
  if (hidden <= 0) return '';
  const tens = Math.floor(hidden / 10) % 10;
  const ones = hidden % 10;
  // 11–14 — всегда «строк»: это исключение из обоих правил.
  const many = tens === 1 ? true : ones === 1 ? false : ones >= 2 && ones <= 4 ? false : true;
  const word = many ? 'строк' : ones === 1 ? 'строка' : 'строки';
  return `⋯ ${hidden} ${word}`;
}
