/**
 * «Идёт чтение» — единый вид ожидания для списков и панелей.
 *
 * Раньше каждое место говорило о загрузке своей строкой: `Читаю структуру…`,
 * `Читаю историю…`, `Загружаю обсуждение…`, `Считаю…`. Слова эти разные, а означают
 * одно, и на медленном ответе (ssh, крупный проект, сеть клиента площадки) они не
 * говорят главного: ЧТО сейчас появится и сколько его будет.
 *
 * Здесь два вида:
 *
 *   • `loadingNote` — короткая строка в углу области: для мест, где список маленький
 *     и мелькание силуэтов только раздражало бы (подсказка в окне, узкая панель);
 *   • `skeleton` — несколько полос на месте будущих строк: там, где список ждут
 *     целиком (структура файла, история, задачи).
 *
 * Полосы — это не «красивая заглушка», а обещание формы: они мигают одной короткой
 * анимацией, пока идёт работа, и гаснут под системным «уменьшить движение».
 * Заглушку снимает тот, кто её поставил: у каждого такого места уже есть отрисовка
 * результата, и она просто заменяет содержимое контейнера.
 */

import { h, svgIcon } from './dom';

/** Строка «идёт чтение»: значок-круговерть и короткое пояснение. */
export function loadingNote(text: string): HTMLElement {
  return h('p', { class: 'loading-note', role: 'status' }, svgIcon('spinner', 13), h('span', {}, text));
}

/**
 * Силуэт будущего списка: `count` полос разной длины.
 *
 * Длина полосы меняется от строки к строке осознанно: ровный столбик одинаковых
 * брусков читался бы как отдельный элемент интерфейса, а не как «здесь будут строки
 * с текстом». Ширина берётся по кругу, чтобы силуэт не дёргался между отрисовками.
 */
export function skeleton(count = 5): HTMLElement {
  const widths = ['82%', '64%', '73%', '56%', '68%', '48%'];
  const box = h('div', { class: 'skeleton', role: 'status', 'aria-label': 'Идёт чтение' });
  for (let index = 0; index < count; index += 1) {
    box.append(h('div', { class: 'skeleton-row', style: { width: widths[index % widths.length]! } }));
  }
  return box;
}
