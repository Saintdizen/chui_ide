/**
 * Беседа панели ассистента. Вкладок может быть много, поэтому всё, что относится
 * к диалогу — история, лента сообщений, правки и приложенный контекст, — живёт
 * в этой структуре, а не в переменных панели: иначе вторая вкладка затирала бы
 * первую. Тип вынесен отдельно, потому что им пользуются и панель, и рендерер
 * потока ответа (`chat-stream.ts`).
 */
export interface ChatSession {
  id: number;
  /** Стабильный идентификатор для сохранения: номер вкладки перезапуск не переживёт. */
  uid: string;
  title: string;
  /** Лента сообщений: своя у каждой беседы, при переключении не перерисовывается. */
  thread: HTMLElement;
  /**
   * Строка очереди в ленте. Отдельным узлом, а не частью истории: история
   * перерисовывается из данных, а очередь живёт своей жизнью и живёт только
   * до конца прогона.
   */
  queueNode?: HTMLElement;
  /**
   * Контекст: то, что уйдёт модели со следующим запросом. После сжатия беседы здесь
   * остаётся резюме — этим `history` и отличается от `transcript`.
   */
  history: ChatMessage[];
  /**
   * Вся переписка — то, что человек видит в ленте и может перечитать. Сжатие
   * контекста её не касается: иначе прочитанные ответы исчезали бы без следа, а
   * выглядело это как «текст обрезался».
   */
  transcript: ChatMessage[];
  /**
   * Беседа сжата: модель получает резюме, а не переписку. Признак нужен ленте —
   * по нему видно, что выше прочитанное, а дальше идёт работа по резюме.
   */
  compacted?: boolean;
  /** Файлы, которые агент изменил именно в этой беседе (правки документов). */
  touched: Map<string, ToggledFile>;
  /** Файлы, которых агент коснулся без правки документа: создал, удалил, перенёс. */
  files: ToolFileChange[];
  /**
   * Что агент предъявил в этой беседе (`present`): та же лента, только без
   * прокрутки — панель артефактов показывает список именно этой вкладки.
   * Не сохраняется: после перезапуска список начинается заново.
   */
  artifacts?: RunArtifact[];
  attachments: ChatAttachment[];
  /**
   * Приложенный контекст, переживший сжатие беседы. После сжатия больше не
   * отправляется, но остаётся здесь, чтобы следующий пересказ не потерял
   * присланный код: резюме пересказывает разговор, а не файлы.
   * Правится вместе с чипами, живёт в памяти и в файле беседы.
   */
  kept?: ChatAttachment[];
  /** Недописанный вопрос: вернулся на вкладку — текст на месте. */
  draft: string;
  /**
   * Где человек читал эту беседу (позиция прокрутки общего `body`).
   *
   * `undefined` — беседу ещё не показывали: её открывают в конце, а не там, где
   * осталась ОБЩАЯ полоса от прошлой вкладки. Число — восстанавливаем как есть,
   * иначе возврат на вкладку прыгал бы в конец поверх читаемой истории.
   */
  scrollTop?: number;
  /** Последний ответ: реальный размер контекста, каким его увидел провайдер. */
  usage?: ChatUsage;
  /**
   * `usage` относится к текущей истории. После сжатия префикс другой, и по старому
   * расходу нельзя судить, попадает ли кеш — его сбросили сами.
   */
  usageFresh?: boolean;
  /**
   * Ходов с последнего сжатия: по нему работает «сжимать чаще». Ход — вопрос
   * человека вместе с ответом, поэтому счётчик растёт один раз за пару.
   */
  turnsSinceCompact?: number;
  /**
   * Накопленный след беседы: шаги, вызовы и расход за всё время. Растёт с каждым
   * прогоном и переживает перезапуск — по нему видно, во сколько обошлась беседа.
   */
  trace?: ChatRunTrace;
  /**
   * Что агент уже прочитал в этой беседе (см. `shared/read-coverage.ts`). Едет в
   * запросе и возвращается в `done`: без этого новый ход заново читал прочитанное
   * (замер — 23,5 тыс. токенов на 71 тыс. чтений). Переживает перезапуск.
   */
  reads?: ReadCoverageSnapshot;
  /**
   * Трасса последнего прогона в этой беседе: что ушло модели, шаги, время.
   * Живёт только в памяти — это диагностика, а не часть переписки: в файл беседы
   * она не едет, иначе история распухла бы выводами инструментов.
   */
  run?: ChatRunLog;
  /**
   * Набор инструментов этой беседы. Не задан — берётся общий из настроек; выбор
   * в композере пишется сюда, поэтому «разговор про рефакторинг» и «разговор про
   * релиз» не навязывают друг другу свой набор. Переживает перезапуск.
   */
  toolPreset?: ToolPresetId;
  /**
   * Цель работы: то, что агент доводит до конца, а не отвечает за один ход.
   * Живёт в беседе, а не в прогоне, — поэтому переживает и ход, и перезапуск.
   * Закрытая цель остаётся здесь же: по ней видно, ради чего шла работа.
   */
  goal?: ChatGoal;
  /**
   * План последнего прогона. Хранится в беседе, а не только в панели: панель
   * одна на все вкладки, и без этого переключение на другую беседу показывало
   * бы ей чужой план (или пустоту вместо своего).
   */
  plan?: PlanStep[];
  /**
   * Планы прошлых прогонов: что уже сделано и когда. Новый план вытесняет
   * текущий сюда, поэтому по ленте видно, как работа шла по шагам, а не только
   * её последнее состояние. Живёт в беседе и переживает перезапуск.
   */
  planHistory?: PlanArchiveEntry[];
  /**
   * Очередь вопросов: то, что человек написал, пока шёл ответ. Стоп — не отказ от
   * набранного, поэтому вопрос не выбрасывается, а встаёт здесь и уходит сам,
   * когда прогон закончится. Не сохраняется: без прогона очередь бессмысленна.
   */
  queue?: QueuedPrompt[];
  /**
   * Снимки «как было до вопроса». Только в памяти: откат нужен внутри сессии, а
   * держать на диске тексты всех тронутых файлов дороже, чем польза от этого.
   */
  checkpoints?: Checkpoint[];
  /** Текущий ход: правки `applyAgentEdits` досыпают в него снимки файлов. */
  activeCheckpoint?: Checkpoint;
}

/** Вопрос, ждущий своей очереди: текст отправки и что было к нему приложено. */
export interface QueuedPrompt {
  text: string;
  /** Вложения — те же, что ушли бы с вопросом: картинки и куски контекста. */
  attachments: ChatAttachment[];
}

/**
 * Куда прокрутить ленту при переходе на вкладку `next`.
 *
 * Возвращает `number` — позицию, куда встать, или `'end'` — в конец ленты. `null`
 * значит «не трогать совсем» — так пока зовёт только один случай: беседу скрыли и
 * показали заново, и браузер позицию уже сохранил сам.
 *
 * Работает в паре со `scrollTop` на `ChatSession`: там `undefined` значит «ещё не
 * показывали». Первое открытие ставит конец (свежая беседа и старая, открытая
 * впервые, читаются с последнего сообщения), а дальше возврат восстанавливает
 * место, где человек остановился.
 *
 * Вынесено из `activate` без DOM: это единственное здесь, что можно проверить
 * тестом, а сам `scrollTop` в jsdom ничего не докажет.
 */
export function scrollTargetFor(next: ChatSession): number | 'end' {
  return next.scrollTop ?? 'end';
}

/**
 * Где в контексте (`history`) лежит вопрос, который в ленте (`transcript`) стоит
 * на позиции `index`. `-1` — этого вопроса в контексте нет.
 *
 * Зачем это нужно. Ленту рисуют по `transcript`, а модель получает `history`, и
 * после сжатия беседы это РАЗНЫЕ массивы: в `history` остаётся резюме и пара
 * служебных сообщений, а `transcript` хранит всю переписку. Кнопка «Править»
 * получала номер из ленты и резала им контекст — то есть отрезала не тот вопрос.
 *
 * Считаем по содержимому, а не арифметикой: у сообщений нет общих идентификаторов,
 * и любая формула «индекс плюс сдвиг» не выдержит очереди и служебных вставок.
 *
 * Повторения считаются с КОНЦА ленты. Это тонкость, на которой легко ошибиться:
 * сжатие съедает только начало переписки, поэтому повтор, который в ленте идёт
 * вторым, в контексте может оказаться ЕДИНСТВЕННЫМ. Счёт же от начала отсёк бы
 * пропавшее первое вхождение и вернул «не найдено» — человеку сказали бы, что
 * правка невозможна, хотя она возможна.
 *
 * Отсюда же следствие: «тот же вопрос» — это и текст, и картинки. Два «глянь»
 * с разными снимками — разные вопросы.
 */
export function contextIndexOf(
  transcript: readonly ChatMessage[],
  history: readonly ChatMessage[],
  index: number,
): number {
  if (index < 0 || index >= transcript.length) return -1;
  const target = transcript[index]!;
  // Картинки — часть вопроса: два «глянь» с разными снимками — это два разных
  // вопроса, и правка второго не должна попадать в первый.
  const sameAs = (message: ChatMessage): boolean =>
    message.role === 'user' &&
    message.content === target.content &&
    (message.images?.length ?? 0) === (target.images?.length ?? 0) &&
    (message.images ?? []).every((image, at) => image === target.images?.[at]);

  // Сколько таких же вопросов идёт в ленте ПОСЛЕ этого: столько же отступаем от
  // конца контекста. Считаем с конца — сжатие режет начало, и повтор, второй в
  // ленте, в контексте часто единственный (см. комментарий к функции).
  let after = 0;
  for (let i = index + 1; i < transcript.length; i += 1) {
    if (sameAs(transcript[i]!)) after += 1;
  }

  for (let i = history.length - 1; i >= 0; i -= 1) {
    if (!sameAs(history[i]!)) continue;
    if (after === 0) return i;
    after -= 1;
  }
  return -1;
}

/**
 * Где в ленте (`transcript`) стоит вопрос, лежащий в контексте (`history`) на
 * позиции `index`. `-1` — этого вопроса в ленте нет.
 *
 * Обратная задача к `contextIndexOf`, и нужна она для «Повторить»: контекст
 * режется номером вопроса, а лента должна резаться по тому ЖЕ вопросу.
 *
 * Где именно режутся массивы, важно. Лента длиннее контекста (она хранит то,
 * что сжатие уже свёрнуто в резюме), поэтому вопрос из начала контекста может
 * встречаться в ленте несколько раз, а вопрос из конца — ровно один.
 *
 * Берём ПОСЛЕДНЕЕ совпадение: повтор идёт от последнего вопроса, а «Повторить»
 * нажимают, чтобы переделать именно его. Первое совпадение отрезало бы ленту по
 * старому такому же вопросу — человек нажал бы «повтори», а лента схлопнулась
 * бы до середины переписки.
 */
export function findThreadIndex(
  session: Pick<ChatSession, 'transcript' | 'history'>,
  asked: ChatMessage,
  index: number,
): number {
  // Страховка от рассинхрона: если по номеру в контексте лежит ДРУГОЙ вопрос
  // (лента и контекст разъехались), искать по нему бессмысленно.
  if (index < 0 || session.history[index] !== asked) return -1;

  const sameAs = (message: ChatMessage): boolean =>
    message.role === 'user' &&
    message.content === asked.content &&
    (message.images?.length ?? 0) === (asked.images?.length ?? 0) &&
    (message.images ?? []).every((image, at) => image === asked.images?.[at]);

  for (let i = session.transcript.length - 1; i >= 0; i -= 1) {
    if (sameAs(session.transcript[i]!)) return i;
  }
  return -1;
}
