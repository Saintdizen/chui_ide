/**
 * Подпись вкладки терминала: имя окна от программы (OSC 0/2) ужимается до читаемого.
 *
 * Оболочка называет окно приглашением целиком — `dethmond@LOQ: ~/PROJECTS/GITHUB/chui_ide`.
 * Такой строке тесно даже в полосе дока: путь в ней — самая длинная и самая бесполезная
 * часть, потому что сессии различаются по КОНЦУ каталога, а не по его началу. Поэтому
 * от пути остаётся последний сегмент (домашний каталог помечается `~`), а полное имя
 * уходит в подсказку вкладки — целиком его видно на наведении.
 *
 * Правило чистое (строка → строка), поэтому проверяется без окна и без pty.
 */

/** Сколько знаков терпит подпись вкладки: дальше полоса дока уезжает в прокрутку. */
const MAX_LABEL = 26;

export function shortenShellTitle(title: string): string {
  const text = title.trim();
  if (text === '') return text;

  // `user@host: <путь>` — приглашение bash и zsh. Прочие имена («vim notes.md»,
  // «npm run dev») коротки и целиком в сути: их не трогаем.
  const match = /^(.*?):\s+(\S.*)$/.exec(text);
  if (!match) return text;

  const head = match[1];
  const path = match[2].replace(/\/+$/, '');
  // Домашний каталог и корень уже короткие: отнимать у них нечего.
  if (path === '' || path === '~' || path === '/') return text;

  const tail = path.slice(path.lastIndexOf('/') + 1);
  // Домашний каталог оставляем помеченным: `~/chui_ide` короче полного пути и при
  // этом сразу говорит, где искать сессию.
  const home = path.startsWith('~/') ? '~/' : '';
  const dir = `${home}${tail}`;
  const label = `${head}: ${dir}`;
  if (label.length <= MAX_LABEL) return label;

  // Длинное имя пользователя и хоста съедает всю подпись. Для вкладки важнее каталог:
  // имя машины повторяется у всех сессий одного окна, а различает их именно папка.
  if (dir.length <= MAX_LABEL) return dir;
  // И каталог бывает длинным: режем его с начала, оставляя хвост — различаются сессии
  // хвостом, а не началом пути.
  return `…${dir.slice(-(MAX_LABEL - 1))}`;
}
