/**
 * Метрики шрифта: сколько пикселей занимает знак и строка.
 *
 * Редактору каждый кадр нужно переводить «столбец ↔ пиксель»: поставить каретку,
 * нарисовать выделение, попасть мышью в символ. Для этого мало знать кегль — нужна
 * ширина клетки знака и высота строки. У моноширинного шрифта, которым набран код,
 * ширина у всех знаков одна, и это главное упрощение: раскладка строки сводится к
 * умножению числа знаков на ширину клетки, без измерения каждого слова.
 *
 * Исключения из «все знаки одинаковые» — широкие и нулевые:
 *
 *   • иероглиф, эмодзи, корейская слоговая занимают две клетки. Если считать их за
 *     одну, каретка в китайской строке уедет влево от настоящего места;
 *   • комбинирующий знак (диакритика поверх буквы) и соединитель нулевой ширины не
 *     занимают клетки вовсе: «е́» — одна клетка, а не две.
 *
 * Поэтому ширина знака — это его КОДОВАЯ ТОЧКА, разложенная на клетки: 0, 1 или 2.
 * Таблица широких диапазонов не выдумана — это свойство Юникода East Asian Width,
 * но в JS его регуляркой не спросить (это не свойство кодовой точки, а отдельная
 * таблица), поэтому диапазоны перечислены здесь.
 *
 * Ширину клетки даёт шрифт: её измеряет DOM-часть (`measureFont`). Здесь — только
 * арифметика поверх уже известной ширины, чтобы раскладку строки можно было проверять
 * без браузера.
 */

/**
 * Ширина знака и строки — всё, что нужно раскладке. Ширина клетки берётся из
 * измерения шрифта: у моноширинных она одна на весь шрифт.
 */
export interface GlyphMetrics {
  /** Ширина одной клетки знака в пикселях (у моноширинного шрифта — у всех одна). */
  readonly charWidth: number;
  /** Высота строки в пикселях (межстрочный интервал включён). */
  readonly lineHeight: number;
  /** Сколько столбцов занимает табуляция: знак переходит к следующему кратному этой величине. */
  readonly tabSize: number;
  /** Ширина кодовой точки в пикселях: 0, одна или две клетки. */
  widthOf(codePoint: number): number;
}

/**
 * Широкие знаки (East Asian Width = Wide или Fullwidth) — две клетки.
 *
 * Диапазоны те же, что у любого редактора кода: CJK, корейское письмо, полноширинные
 * формы, частые эмодзи. Точный список Юникода тут не нужен — важны ходовые письмена,
 * а редкий знак, попавший в «две клетки» вместо одной, сдвинет каретку меньше, чем
 * иероглиф, посчитанный за одну.
 */
function isWide(codePoint: number): boolean {
  return (
    (codePoint >= 0x1100 && codePoint <= 0x115f) || // хангыль-чамо
    (codePoint >= 0x2e80 && codePoint <= 0x303e) || // CJK-радикалы, знаки
    (codePoint >= 0x3041 && codePoint <= 0x33ff) || // кана, CJK-совместимость
    (codePoint >= 0x3400 && codePoint <= 0x4dbf) || // CJK расширение A
    (codePoint >= 0x4e00 && codePoint <= 0x9fff) || // CJK основные иероглифы
    (codePoint >= 0xa000 && codePoint <= 0xa4cf) || // и-слоги
    (codePoint >= 0xac00 && codePoint <= 0xd7a3) || // хангыль-слоги
    (codePoint >= 0xf900 && codePoint <= 0xfaff) || // CJK-совместимость идеографов
    (codePoint >= 0xfe10 && codePoint <= 0xfe19) || // вертикальные формы
    (codePoint >= 0xfe30 && codePoint <= 0xfe6f) || // CJK-совместимость форм
    (codePoint >= 0xff00 && codePoint <= 0xff60) || // полноширинные формы ASCII
    (codePoint >= 0xffe0 && codePoint <= 0xffe6) || // полноширинные знаки
    (codePoint >= 0x1f300 && codePoint <= 0x1f64f) || // эмодзи
    (codePoint >= 0x1f900 && codePoint <= 0x1f9ff) || // доп. эмодзи
    (codePoint >= 0x20000 && codePoint <= 0x3fffd) // CJK расширение B и далее
  );
}

/**
 * Нулевая ширина: знак рисуется поверх соседнего, своей клетки не занимает.
 * Свойства Юникода тут доступны прямо в регулярке — в отличие от East Asian Width.
 * Соединители и селекторы начертания проверяются отдельно: в классе символов ZWJ
 * соседствовал бы с эмодзи, а такое правило считает опечаткой (оно ждёт чередование),
 * хотя здесь мы сверяем ОДНУ кодовую точку.
 */
const combiningMark = /^[\p{Mn}\p{Me}]$/u;

function isZeroWidth(codePoint: number): boolean {
  if (codePoint === 0x200b || codePoint === 0x200c || codePoint === 0x200d) return true; // ZWSP/ZWNJ/ZWJ
  if (codePoint === 0xfeff) return true; // метка порядка байт
  if (codePoint >= 0xfe00 && codePoint <= 0xfe0f) return true; // селекторы начертания
  return combiningMark.test(String.fromCodePoint(codePoint));
}

/** Сколько клеток занимает знак: 0 — нулевой ширины, 2 — широкий, 1 — обычный. */
export function cellsOf(codePoint: number): number {
  if (isZeroWidth(codePoint)) return 0;
  return isWide(codePoint) ? 2 : 1;
}

/**
 * Метрики моноширинного шрифта по готовой ширине клетки. Так их задают и тесты:
 * раскладке всё равно, откуда взята ширина — из измерения или из константы.
 */
export function monospaceMetrics(charWidth: number, lineHeight: number, tabSize = 4): GlyphMetrics {
  return {
    charWidth,
    lineHeight,
    tabSize,
    widthOf: (codePoint: number) => cellsOf(codePoint) * charWidth,
  };
}

/**
 * Измерить моноширинный шрифт прямо в узле редактора.
 *
 * Меряем НЕ на canvas, а скрытым элементом внутри редактора: canvas-замер ширины
 * клетки расходится с настоящим шагом глифов (у шрифта кода 14 px разница
 * доходила до 0.4%), а на длинной строке это копится в сдвиг каретки на пару
 * пикселей. Элемент внутри редактора видит ровно тот шрифт, кегль и межбуквенное
 * расстояние, которыми набран текст, и потому врёт только на округлении.
 *
 * Берём строку из десяти нулей и делим на десять: одиночный знак округляется
 * заметно сильнее. Высота строки приходит готовой (её задаёт стиль).
 *
 * Требует DOM: вызывается при создании представления, не из чистой логики.
 */
export function measureFont(container: HTMLElement, fontSize: number, lineHeight: number, tabSize = 4): GlyphMetrics {
  const reference = '0000000000';
  const probe = document.createElement('span');
  probe.textContent = reference;
  // `pre` — чтобы строка не переносилась и не сжималась; скрытость через visibility,
  // а не `display: none`: скрытый узел не измерить.
  probe.style.cssText = 'position:absolute;visibility:hidden;white-space:pre;pointer-events:none';
  container.append(probe);
  const measured = probe.getBoundingClientRect().width;
  probe.remove();

  // Запасной путь, если измерить не удалось (узел не прикреплён): прикидка по кеглю.
  const charWidth = measured > 0 ? measured / reference.length : fontSize * 0.6;
  return monospaceMetrics(charWidth, lineHeight, tabSize);
}
