/**
 * «Мягкая» линейка переноса (TASKS 49).
 *
 * Перенос строк уже есть (`wrap-model.ts`): длинная строка разрезана на отрезки, и
 * каждый рисуется своим рядом. Но на глаз продолжение не отличить от новой строки —
 * особенно когда код с отступом, и перенесённый кусок начинается ровно там же, где
 * начинаются соседние строки блока.
 *
 * Линейка решает это одним штрихом: у рядов-продолжений слева от текста стоит тонкая
 * вертикаль. Место у неё ровно одно — ЗА отступом строки и ПЕРЕД первым знаком ряда:
 *
 *   - левее отступа — спорит с направляющими отступов (`indent-guides.ts`), и два вида
 *     вертикальных штрихов в одной колонке читаются как один сломанный;
 *   - правее первого знака — наезжает на текст.
 *
 * Поэтому считаем её в координатах СТРОКИ (от края текста), а не ряда: отступ строки
 * у всех её отрезков общий, и линейка у всех встаёт в одну колонку — по ней и видно,
 * что это одна строка.
 *
 * Второй отрезок и дальше отступ не повторяет (он один на строку), поэтому у них
 * линейка стоит на той же координате — ровно там, где начинался бы отступ.
 */

/** Опции раскладки: ширина знака и ширина табуляции в знаках. */
export interface WrapGuideOptions {
  /** Ширина одного знака моноширинного шрифта в пикселях. */
  charWidth: number;
  /** Табуляция в знаках — как её считает раскладка строки. */
  tabSize: number;
}

/** Отступ в знаках: пробелы и табуляции до первого прочего знака. */
export function indentColumnsOf(text: string, tabSize: number): number {
  const tab = Math.max(1, Math.floor(tabSize));
  let columns = 0;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === ' ') columns += 1;
    else if (ch === '\t') columns += tab - (columns % tab);
    else break;
  }
  return columns;
}

/**
 * X линейки переноса в пикселях от левого края строки текста.
 *
 * `null` — линейку не рисуем:
 *  - строка не переносится (отрезок один) — рисовать нечего;
 *  - строка пустая или из одних пробелов — переносить нечего, и штрих висел бы
 *    в пустоте;
 *  - текст начинается с самого края (отступ 0) — тогда линейка совпала бы с краем
 *    текста и легла бы прямо на первый знак.
 *
 * Вырожденная ширина знака (0, отрицательная, NaN) тоже даёт `null`: иначе
 * координата уехала бы в NaN и стиль не применился бы вовсе — штрих молча пропал бы.
 */
export function wrapGuideX(text: string, segmentCount: number, options: WrapGuideOptions): number | null {
  if (segmentCount < 2) return null;
  if (text.trim().length === 0) return null;
  const charWidth = options.charWidth;
  if (!Number.isFinite(charWidth) || charWidth <= 0) return null;
  const indent = indentColumnsOf(text, options.tabSize);
  if (indent === 0) return null;
  const x = indent * charWidth;
  return Number.isFinite(x) ? x : null;
}
