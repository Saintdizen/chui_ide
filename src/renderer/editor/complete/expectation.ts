/**
 * Что ждёт место под курсором: значение или тип.
 *
 * Это первый шаг «умного» дополнения. Полноценное, как в больших IDE, фильтрует по
 * ОЖИДАЕМОМУ ТИПУ — а для этого нужна модель типов, которой у нас нет: типы знает
 * языковой сервер, и он же сам сужает свой ответ по контексту. Здесь то, что можно
 * вывести из самого текста: в позиции значения (`= `, `return `, аргумент) имена типов
 * и ключевые слова не нужны, а после `:` наоборот — нужны типы, а не переменные.
 *
 * Правило нарочно простое и предсказуемое: ошибиться им можно только в одну сторону —
 * спрятать лишнее, но не подсунуть неподходящее. Поэтому оно включается отдельным
 * сочетанием (Ctrl+Shift+Space), а не работает всегда.
 */

/** Чего ждёт место. `any` — решать не берёмся, показываем всё как обычно. */
export type Expectation = 'value' | 'type' | 'any';

/** Знаки, после которых начинается выражение или значение. */
const VALUE_BEFORE = new Set(['=', '(', ',', '+', '-', '*', '/', '%', '<', '>', '&', '|', '[', '{', '!', '?', ':']);

/**
 * Что ожидается в позиции.
 *
 * Смотрим на текст строки ПЕРЕД курсором, а не вокруг него: подсказка появляется там,
 * где человек печатает, и знак перед ним говорит больше, чем следующий.
 *
 *   • после `:` (аннотация, тип поля) — тип;
 *   • после `=`, `return`, запятой в аргументах, открывающей скобки — значение;
 *   • после `->` (тип возврата) — тип;
 *   • всё остальное — `any`: угадывать по одному знаку не стоит.
 *
 * `language` не нужен: правила общие для Python и TypeScript, а расхождения двух языков
 * тут не стоят отдельной грамматики.
 */
export function expectedAt(before: string): Expectation {
  const text = before.trimEnd();
  if (!text) return 'any';

  // `->` — тип возврата: значение там не пишут.
  if (text.endsWith('->')) return 'type';
  // `:` в конце — аннотация. Двойное `::` (Python-срез, CSS-псевдоэлемент) не считаем.
  if (text.endsWith(':') && !text.endsWith('::')) return 'type';
  // `=` (но не `==`, `<=`, `>=`, `!=`) — присваивание: справа значение.
  if (/(^|[^=!<>])=$/.test(text)) return 'value';
  // Ключевые слова, после которых идёт значение.
  if (/\b(?:return|yield|await|raise|assert|in|is|and|or|not|case)$/.test(text)) return 'value';

  const last = text.at(-1) ?? '';
  if (VALUE_BEFORE.has(last)) return 'value';
  return 'any';
}

/**
 * Подходит ли подсказка месту.
 *
 * Имя типа (`класс`, `интерфейс`, `структура`) в позиции значения бесполезно — его
 * нельзя присвоить, — а переменная после `:` не заменяет тип. Всё незнакомое оставляем:
 * спрятать нужное хуже, чем показать лишнее.
 */
export function fitsExpectation(expectation: Expectation, kindLabel: string): boolean {
  if (expectation === 'any') return true;
  const kind = kindLabel.toLowerCase();
  const isType = /^(класс|интерфейс|структура|перечисление|тип|enum)/.test(kind);
  const isValue = /^(функция|метод|переменная|константа|поле|свойство|параметр|модуль|слово)/.test(kind);
  if (expectation === 'value') return !isType;
  // В позиции типа оставляем типы и всё неопознанное (ключевые слова языка, имена
  // из файла): их роль по подписи не видна, а среди них бывают нужные.
  return !isValue || isType;
}

/**
 * Отобрать подсказки под место. Порядок сохраняется: его задал сервер или частотность,
 * и переупорядочивать чужой ответ под свою эвристику нечестно.
 */
export function filterByExpectation<T extends { detail: string }>(items: readonly T[], expectation: Expectation): T[] {
  if (expectation === 'any') return [...items];
  return items.filter((item) => fitsExpectation(expectation, item.detail));
}
