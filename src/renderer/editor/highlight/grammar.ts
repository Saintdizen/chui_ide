/**
 * Грамматика подсветки: как текст строки превращается в токены.
 *
 * Подсветка построчная и с состоянием — по той же причине, что и всё остальное в
 * редакторе: файл бывает в сто тысяч строк, а видно из него сорок. Строку можно
 * разобрать отдельно от остальных, если знать, в каком «режиме» она начинается:
 * внутри блочного комментария, внутри шаблонной строки или в обычном коде. Это и есть
 * состояние строки — число, которое грамматика принимает на вход и отдаёт на выход.
 *
 * Число, а не объект: состояния четыре-пять на язык, и по числу их дёшево сравнивать —
 * именно сравнением ловится «дальше всё как было» (см. `highlighter.ts`), из-за чего
 * правка в начале файла не заставляет переразбирать файл целиком.
 *
 * Разметка строки — массив токенов с границами в единицах UTF-16 (как и смещения в
 * модели текста). Между токенами дыр нет: всё, что не окрашено, — токен `PLAIN`.
 * Так представлению не приходится думать о переходах.
 *
 * Грамматики наши, но говорят они с палитрой теми же типами токенов, что и тема
 * (`tokens.ts`) — поэтому цвета берутся из одной таблицы с чатом и остальной IDE.
 */

import type { Token } from './tokens';

export type { Token } from './tokens';

/** Что вернула грамматика про одну строку: её токены и состояние СЛЕДУЮЩЕЙ строки. */
export interface LineResult {
  readonly tokens: Token[];
  /** Режим, в котором начнётся следующая строка. */
  readonly state: number;
}

/** Разбор одной строки. `state` — режим, в котором строка начинается. */
export interface Grammar {
  /** Идентификатор языка — тот же, что в реестре языков приложения. */
  readonly id: string;
  line(text: string, state: number): LineResult;
}

/**
 * Обычный режим: код, разметка, что угодно, кроме продолжения многострочной
 * конструкции. Ноль — состояние всех грамматик по умолчанию, поэтому не нужно
 * помнить, с какого числа начинаются «свои» режимы языка.
 */
export const ST_NORMAL = 0;

/**
 * Незакрытый блочный комментарий. Общий для всех C-подобных языков и разметки —
 * вынесен сюда, потому что и HTML-комментарий, и `/* … *​/` — это одно и то же
 * поведение: до конца строки всё комментарий, ищем закрывающую пару.
 */
export const ST_BLOCK_COMMENT = 1;

/** Незакрытая шаблонная строка (обратные кавычки) — переносится на следующую строку. */
export const ST_TEMPLATE = 2;

/** Незакрытая тройная строка `"""`. */
export const ST_TRIPLE_DOUBLE = 3;

/** Незакрытая тройная строка `'''`. */
export const ST_TRIPLE_SINGLE = 4;

/** Режим, зарезервированный под конкретный язык: дальше каждая грамматика считает сама. */
export const ST_LANGUAGE_BASE = 16;
