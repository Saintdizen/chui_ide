/**
 * Кэш токенов на всё приложение: разобрать строку один раз и переиспользовать результат.
 *
 * У `LineHighlighter` уже есть свой кэш по строкам — но только ВНУТРИ одного экземпляра.
 * А подсветка вне редактора (копия кода под наведением, сравнение, блоки кода в чате)
 * создаёт разборщик заново на каждую отрисовку: прокрутил копию, шевельнул сравнение,
 * пришёл новый кадр ленты — и те же самые строки разбираются снова. Свой кэш тут не
 * спасает: он умирает вместе с экземпляром.
 *
 * Здесь кэш ОБЩИЙ и переживает экземпляры. Ключ — язык, состояние строки и текст:
 * разбор построчный и детерминированный, поэтому одинаковые (язык, режим, текст) дают
 * те же токены где угодно. Память ограничена размером кэша (вытесняем самый старый) —
 * строка в тысячу знаков даёт десяток токенов, поэтому значение держим по числу строк,
 * а не по байтам: так предел понятен и не зависит от длины строк.
 *
 * Модуль чистый: ни DOM, ни модели текста — только грамматика и текст.
 */

import type { Grammar, LineResult } from './grammar';

/** Сколько строк держим по умолчанию. Больше — уже не «горячие» строки, а весь файл. */
export const DEFAULT_TOKEN_CACHE_LIMIT = 5000;

export class TokenCache {
  /** Порядок вставки — порядок свежести: первым вытесняется самый старый. */
  private readonly entries = new Map<string, LineResult>();

  constructor(private readonly limit: number = DEFAULT_TOKEN_CACHE_LIMIT) {}

  /** Сколько строк сейчас в кэше — для проверок. */
  get size(): number {
    return this.entries.size;
  }

  /** Забыть всё: например, сменилось оформление или язык. */
  clear(): void {
    this.entries.clear();
  }

  /**
   * Разобрать строку, взяв результат из кэша, если он там уже есть. Попадание освежает
   * запись (переносим её в конец) — так вытесняется давно не спрашиваемая строка, а не
   * та, что была вставлена раньше.
   */
  line(grammar: Grammar, text: string, state: number): LineResult {
    const key = `${grammar.id}\u0000${state}\u0000${text}`;
    const hit = this.entries.get(key);
    if (hit) {
      // Свежесть: переносим запись в конец порядка вставки.
      this.entries.delete(key);
      this.entries.set(key, hit);
      return hit;
    }

    const result = grammar.line(text, state);
    this.entries.set(key, result);
    if (this.entries.size > this.limit) {
      const oldest = this.entries.keys().next().value;
      if (oldest !== undefined) this.entries.delete(oldest);
    }
    return result;
  }
}

/**
 * Общий кэш приложения. Его берут и редактор, и подсветка вне редактора — тогда строка
 * кода из чата и та же строка в редакторе разбираются один раз на двоих.
 */
export const sharedTokens = new TokenCache();
