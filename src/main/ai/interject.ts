/**
 * Сказанное на ходу: вопрос, который человек вставляет в идущий прогон.
 *
 * Отдельно от `PauseGate` и от очереди renderer'а (`chat-queue.ts`), потому что
 * у них разные судьбы. Очередь renderer'а — «отправь после ответа», она ждёт
 * конца и живёт в беседе; эта — «скажи агенту сейчас», и она умирает вместе с
 * прогоном, в который её сказали.
 *
 * Почему очередь, а не одно поле: человек может дописать второе, пока агент ещё
 * не дошёл до границы шага. Терять нельзя ни то, ни другое.
 *
 * Строкой, а не `ChatMessage`: вклейка в историю — дело цикла шагов (там решается,
 * каким голосом и с какой пометкой она поедет), а здесь — только хранение.
 */
export class InterjectQueue {
  private items: string[] = [];
  /**
   * Есть ли кому это сказать прямо сейчас.
   *
   * Знает цикл шагов, а не очередь: реплика в пустоту — не принятая реплика, и
   * человек должен узнать об этом сразу, а не когда-нибудь потом. Заодно это
   * защита от протечки: сказанное вчерашним прогоном не прозвучит в сегодняшнем.
   */
  private listening = false;

  /** Прогон начался (`service.chat`): реплики с этой минуты доходят. */
  open(): void {
    this.listening = true;
    this.items = [];
  }

  /** Прогон кончился: сказанное не дожило до модели и больше никому не нужно. */
  close(): void {
    this.listening = false;
    this.items = [];
  }

  /** Сколько ждёт. Нужно, чтобы событие в ленте не врало о пустой очереди. */
  get size(): number {
    return this.listening ? this.items.length : 0;
  }

  /** Добавить сказанное на ходу. Пустое (и пробельное) — не реплика, а промах Enter. */
  push(text: string): boolean {
    const trimmed = text.trim();
    if (!this.listening) return false;
    if (trimmed.length === 0) return false;
    this.items = [...this.items, trimmed];
    return true;
  }

  /**
   * Забрать всe разом, очистив очередь.
   *
   * Всё сразу, а не по одному: шаг — это один запрос к модели, и два сказанных
   * подряд вопроса должны доехать до неё вместе, в том порядке, как их писали.
   * Разнести их по шагам значило бы придумать ответ на первый, не зная второго.
   */
  takeAll(): string[] {
    if (this.items.length === 0) return [];
    const taken = this.items;
    this.items = [];
    return taken;
  }

  clear(): void {
    this.items = [];
  }
}
