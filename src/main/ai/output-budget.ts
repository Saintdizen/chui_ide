/**
 * Потолки вывода: сколько символов инструмент может отдать модели за вызов и за шаг.
 *
 * Отдельно от обрезки (`output-trim.ts`): числа читают все — сборка промпта,
 * бюджет шага, `read` с его пачками, — а правят их редко и по замеру. Держать их
 * в одном файле с обрезкой значило бы искать цифру в 500 строках вокруг.
 */

/**
 * Ограничение вывода одного вызова: без него один файл на 2 МБ съест весь
 * контекст модели.
 *
 * 18 000 символов — примерно 5 000 токенов. Было 45 000 (12 000 токенов), но
 * замер по журналу прогонов показал цену: токен, попавший в контекст, платится
 * один раз целиком и ещё ~30 раз по 10% (он в кеше префикса всех следующих
 * шагов), то есть множитель ≈ 4. Один вызов на 12 000 токенов стоит как 48 000.
 * Всё, что не влезло, не теряется: `clipText` пишет остаток в spill-файл и
 * называет путь — модель дочитает диапазоном, если он правда нужен.
 */
export const MAX_OUTPUT_CHARS = 18_000;
/** Оценка, а не токенизатор провайдера: кириллица не должна обходить символьный потолок. */
export const MAX_OUTPUT_TOKENS = 5_200;

/**
 * Сколько символов вывода шаг отдаёт модели всего. Предела на вызов мало: агент
 * читает по три файла за шаг, и это 135 000 символов — после чего обрезка истории
 * выбрасывает ходы целиком. Бюджет шага делает цену шага предсказуемой, а
 * `MIN_OUTPUT_CHARS` не даёт инструменту ответить пустотой.
 *
 * Свежие результаты инструментов провайдер оплачивает целиком (в кеш они
 * попадают только со следующего запроса), поэтому бюджет шага — самая дорогая
 * часть истории. Замер: в среднем вызов отдаёт 3 000 токенов, так что 24 000
 * символов (≈6 700 токенов) — это два-три щедрых вызова; прежние 60 000
 * срабатывали редко, но каждый такой шаг стоил как четыре обычных прогона.
 */
export const STEP_OUTPUT_CHARS = 24_000;

/**
 * Минимум на один вызов, даже когда бюджет шага уже исчерпан. Пустой ответ модель
 * поймёт как «инструмент ничего не вернул» и позовёт его снова; честнее отдать
 * начало (или хвост) с пометкой, что текст лежит в файле.
 */
export const MIN_OUTPUT_CHARS = 1_500;
/**
 * Потолок на вывод одного инструмента, в символах.
 *
 * Общий потолок (`MAX_OUTPUT_CHARS`) — это «сколько бывает полезно в худшем
 * случае», а не норма: `list` на 18 000 символов не нужен никогда (две сотни
 * имён), `read` на 18 000 — это 400 строк, которые модель просила прочитать.
 * Платится же каждый символ: токен живёт в контексте до конца диалога.
 *
 * Числа — доля от прежнего единого потолка по тому, сколько в среднем
 * оказывается полезным: у `list`/`search` ответ интерпретируется целиком
 * (модель читает его как карту), у `read` — тоже, но пачкой файлов, у команды
 * и проверок важен хвост. Инструмента, которого здесь нет, общий предел не
 * отпугивает: `Прочее` — это он и есть.
 */
export const TOOL_OUTPUT_CHARS: Record<string, number> = {
  // Перечисления: имя + строка контекста. Длиннее — уже не список, а дамп.
  list: 6_000,
  project_map: 4_000,
  search: 8_000,
  history: 6_000,
  lsp: 6_000,
  // Чтение содержимого: пачка файлов, но каждый — частями.
  read: MAX_OUTPUT_CHARS,
  read_image: 2_000,
  // Вывод процессов: важен хвост, а начало часто шум (приветствие сборки).
  // Ключи — имена инструментов из `AGENT_TOOLS`, а не действия: `run` тут стоял
  // с тех пор, как команда звалась действием. Имя сменилось на `terminal`, ключ
  // не за ним — и настоящий шелл молча получал общий предел 18 000 вместо 12 000
  // (замер 26.10: `TOOL_OUTPUT_CHARS` не знает `terminal`, `terminalOpen`…,
  // а знает несуществующий `run`). Остальные четыре имени терминала — сессия:
  // `terminalOutput` ровно для того и зовут, чтобы прочитать важный хвост.
  terminal: 12_000,
  terminalOutput: 12_000,
  checks: 8_000,
  run_tests: 12_000,
  // Правка и файловые операции: модель уже знает, что писала; ответ — отчёт.
  edit: 4_000,
  file: 4_000,
  terminalList: 4_000,
  // Прочее поведение: ответ и так короткий, потолок — страховка.
  web: 8_000,
  browser: 4_000,
  mcp: 8_000,
  mind: 4_000,
  show: 2_000,
};

/**
 * Сколько символов этот инструмент вправе отдать за вызов: свой потолок, но не
 * больше общего предела. Неизвестное имя (MCP-инструмент, новый) получает общий.
 */
export function toolOutputChars(name: string): number {
  return Math.min(MAX_OUTPUT_CHARS, TOOL_OUTPUT_CHARS[name] ?? MAX_OUTPUT_CHARS);
}

/**
 * Бюджет вывода шага под окно модели.
 *
 * 60 000 символов — это около 17 000 токенов, и на окне 32k один шаг съедал
 * половину: следующий же шаг упирался в переполнение, а промах стоит полного
 * запроса заново плюс выброшенные ходы. Поэтому бюджет — доля окна (12%), но не
 * больше прежнего потолка и не меньше 6 000 символов (иначе инструмент ответит
 * пустотой, и модель позовёт его снова).
 */
export function stepOutputChars(windowTokens: number): number {
  const share = Math.round(windowTokens * 0.12 * 3.5);
  return Math.max(MIN_OUTPUT_CHARS * 4, Math.min(STEP_OUTPUT_CHARS, share));
}
