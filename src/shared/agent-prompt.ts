/**
 * Промпт агентного режима под конкретный набор и права.
 *
 * Меньше слов — не ради экономии самой по себе: совет про инструмент, которого
 * в этом запросе нет, отправляет модель искать обходной путь, и шаг тратится на
 * выяснение «а почему его нет».
 */
export function agentPrompt(preset: ToolPresetId, options: { confirm: boolean }): string {
  const spec = toolPresetSpec(preset);
  const allowed = spec.widen ? null : presetToolNames(preset);
  const hints = AGENT_HINTS.filter((hint) => {
    if (hint.aboutApproval && !options.confirm) return false;
    if (!hint.needs || allowed === null) return true;
    return hint.needs.some((name) => allowed.has(name));
  });
  return hints.map((hint) => hint.text).join('\n');
}
