/**
 * Большие файлы: с какого размера редактор открывает файл только для чтения и где
 * проходит предел, за которым файл не берём вовсе.
 *
 * Большой файл — не ошибка, а факт: миллионы знаков и сотни тысяч строк. Править такое
 * в редакторе тяжело (история, подсветка, языковой сервер), а вот посмотреть — полезно.
 * Поэтому выше порога файл открывается, но ТОЛЬКО для чтения: текст виден, курсор ходит,
 * поиск работает, а ввод и правки — нет. Совсем огромный файл не берём даже на чтение:
 * держать его в памяти редактора незачем.
 *
 * Пороги и решения живут здесь, а не в коде по месту, — по ним же строится и надпись
 * человеку, поэтому «слишком большой» везде значит одно и то же число.
 */

/** Выше этого размера файл открывается ТОЛЬКО для чтения. */
export const LARGE_FILE_BYTES = 2 * 1024 * 1024;

/** Жёсткий предел: файл крупнее в редактор не берём даже на чтение. */
export const MAX_OPEN_BYTES = 16 * 1024 * 1024;

/** Открывать ли файл такого размера только для чтения. */
export function isReadOnlySize(bytes: number): boolean {
  return bytes > LARGE_FILE_BYTES;
}

/** Влезает ли файл такого размера в редактор хоть как-то. */
export function withinOpenLimit(bytes: number): boolean {
  return bytes <= MAX_OPEN_BYTES;
}

/**
 * С какого числа строк раскладка переноса становится дороже пользы.
 *
 * При включённом переносе каждая строка раскладывается на знаки, чтобы узнать,
 * сколько рядов экрана она займёт, — это массив на КАЖДЫЙ знак, и такие массивы
 * строятся для всех строк файла разом. На ста тысячах строк это миллионы чисел
 * в памяти и заметная пауза при открытии — окно замирает ещё до первого кадра.
 *
 * Выше порога считаем ряд за строку: перенос выключен, текст ровный, прокрутка
 * честная. Файл такой длины в редакторе всё равно открывается только для чтения
 * (`isReadOnlySize` его не догоняет — он про байты, а тут про количество строк:
 * сто тысяч коротких строк весят немного, а раскладывать их — та же работа).
 */
export const MAX_WRAP_LINES = 50_000;

/** Раскладывать ли такой файл по строкам переноса. */
export function wrapsByLineCount(lineCount: number): boolean {
  return lineCount <= MAX_WRAP_LINES;
}
