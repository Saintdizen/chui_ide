/**
 * Разметка вызова, попавшая в текст ответа.
 *
 * В режиме «Вопрос» инструменты модели не передаются (`tools` пуст), но
 * не все модели это принимают: часть из них всё равно пишет вызов — в родной
 * разметке провайдера. Своего поля для вызова у ответа нет, и всё это
 * приезжает обычным текстом: человек видит служебные токены вместо ответа.
 *
 * Настоящий случай: модель отвечала вызовами в разметке DSML, а черты в ней —
 * полноширинные (U+FF5C), а не `|`. Регэксп по обычной черте их не ловит,
 * поэтому символ вписан буквой.
 *
 * Фильтр чистый и идемпотентный: один и тот же текст проходит через него
 * и при потоке, и при сохранении, и результат не меняется.
 *
 * Отдельно про поток. Разметка приходит кусками по 2–3 символа, и до самого
 * конца непонятно, разметка это или обычный текст: `｜` может оказаться первым
 * символом пары, а `<tool` — первым символом тега. Поэтому показанным считается
 * только тот текст, который уже не может стать началом вызова, — остальное
 * ждёт (`heldTail`). Удерживается не больше хвоста самой длинной разметки.
 */

/** Самое длинное начало вызова, которое надо придержать до развязки. */
const HOLD_LIMIT = 64;

/** Полноширинные черты разметки DSML. */
const DSML_BAR = '\uFF5C';

/** Раскрытая форма: `<tool_call>…</tool_call>`, `<invoke …>…</invoke>` и родня. */
const BLOCK_TAG =
  /<(?:tool_call|tool_calls|function_call|function_calls|dsml|invoke|tool_use|antml:invoke|antml:function_calls)(?:\s[^>]*)?>[\s\S]*?<\/(?:tool_call|tool_calls|function_call|function_calls|dsml|invoke|tool_use|antml:invoke|antml:function_calls)>/gi;

/** Самозакрытая форма: `<tool_call …/>`, `<read …/>` — без пары. */
const SELF_TAG = /<(?:tool_call|tool_calls|function_call|function_calls|dsml|invoke|tool_use)\b[^>]*\/>/gi;

/**
 * Блок DSML в полноширинных чертах: от открывающей пары до закрывающей.
 * Пара не обязательна — модель часто обрывает разметку на полпути, и хвост
 * тоже надо убрать, иначе служебные токены остаются в ответе.
 */
const DSML_BLOCK = new RegExp(
  DSML_BAR.repeat(2) + 'DSML' + DSML_BAR.repeat(2) +
    '[\\s\\S]*?(?:' +
    DSML_BAR.repeat(2) + '\\/?DSML' + DSML_BAR.repeat(2) +
    '|' + DSML_BAR.repeat(2) + '\\/?invoke' + DSML_BAR.repeat(2) +
    '|$)',
  'gi',
);

/**
 * Шаблон вида `[name: arg]` или `[name](arg)`, которым модели подменяют вызов,
 * когда родной протокол недоступен. Берём только известные имена: любой текст
 * в квадратных скобках вырезать нельзя — так пишут и в обычном ответе.
 */
const BRACKET_CALL =
  /\[\s*(?:tool|function|call)?\s*[:=]?\s*[a-z_]*(?:read|write|edit|patch|search|list|run|exec|terminal|fetch|web|git|todo|lsp|browser|apply_patch|apply_edit|tool_[a-z_]+)\s*[(:][\s\S]{0,400}?[)\]]/gi;

/** Три и больше переводов строки, оставшихся от вырезанного блока. */
const TRIPLE_NEWLINE = /\n{3,}/g;

/**
 * Убрать из ответа разметку вызова. Обычный текст возвращается как есть.
 *
 * Правка идёт только вокруг найденных блоков: пробелы и переводы строк
 * внутри самого ответа не переформатируются, иначе код в ответе поехал бы.
 */
export function stripCallMarkup(text: string): string {
  if (!text.includes('<') && !text.includes('[') && !text.includes(DSML_BAR)) return text;
  const without = cutMarkup(text);
  if (without === text) return text;
  // Вырезание блока оставляет пустую строку там, где он стоял, — склеиваем
  // соседние переводы, но не трогаем одиночные.
  return without.replace(TRIPLE_NEWLINE, '\n\n').trim();
}

/**
 * То же, но без подрезки краёв.
 *
 * Потоку нужны смещения: он показывает текст по мере прироста и не может
 * позволить себе, чтобы `trim` сдвинул начало уже показанного. Края подрежет
 * `stripCallMarkup` — когда ответ готов и показывать больше нечего.
 */
export function cutMarkup(text: string): string {
  return text
    .replace(DSML_BLOCK, '')
    .replace(BLOCK_TAG, '')
    .replace(SELF_TAG, '')
    .replace(BRACKET_CALL, '');
}

/**
 * Хвост, который показывать рано: от него ещё может дорасти разметка.
 *
 * Придерживаем две вещи: незакрытую пару полноширинных черт и незакрытый тег
 * в конце текста. Всё остальное уходит человеку сразу — иначе ответ в ленте
 * опаздывал бы на весь блок.
 */
export function heldTail(visible: string): number {
  if (visible.length === 0) return 0;
  // Последняя черта без пары — начало разметки DSML. Держим и отступ перед
  // ней: `\n` — часть того же хвоста, и показав его, мы оставили бы в ленте
  // висящую пустую строку там, где вызов был.
  const bar = visible.lastIndexOf(DSML_BAR);
  if (bar !== -1 && visible.length - bar <= HOLD_LIMIT) {
    // Держим всё до текста перед разметкой, а не только черты. Между первой
    // парой и закрывающей лежит тело вызова (`DSML｜｜invoke …`), и его тоже
    // нельзя показывать: пара черт сама по себе — уже служебный токен.
    // Ищем, где кончается текст: разметка стоит либо в конце ответа, либо
    // отдельным блоком после перевода строки.
    let from = visible.lastIndexOf('\n', bar);
    from = from === -1 ? 0 : from + 1;
    // Если в этой строке до черт был обычный текст — он не разметка.
    return visible.length - from;
  }
  // Незакрытый тег в конце: `<tool_call …` без `>`.
  const lt = visible.lastIndexOf('<');
  if (lt !== -1 && visible.indexOf('>', lt) === -1 && visible.length - lt <= HOLD_LIMIT) {
    const head = visible.slice(lt + 1).toLowerCase();
    // Придерживаем только похожее на вызов: `<b` в обычном тексте ждать нечего.
    if ('tool_call'.startsWith(head) || 'tool_calls'.startsWith(head) || 'invoke'.startsWith(head)) {
      return visible.length - lt;
    }
  }
  return 0;
}
