/**
 * Что делать с прогоном, который просят бросить.
 *
 * Закрывая вкладку с идущим ответом, человек не сказал ни «стоп»,
 * ни «продолжай» — он сказал только «эта вкладка мне больше не нужна».
 * Агент к этому моменту, возможно, уже правит файлы: оборвать
 * молча — потерять работу, а оставить без спроса — продолжать
 * тратить токены за спиной.
 *
 * Здесь только решение по состоянию, без DOM и без RPC: окно рисует
 * ответ, а модуль говорит, какой из трёх.
 */

/** Состояние прогона в момент, когда его просят бросить. */
export type RunLeaving =
  | 'idle'
  /** Агент уже изменил файлы или предложил правки: терять есть что. */
  | 'wrote'
  /** Агент только читал и искал: терять нечего. */
  | 'read';

/** Что предложить человеку. */
export type RunLeaveChoice = 'stop' | 'keep' | 'ask';

/**
 * Выбрать, чего заслуживает закрытие вкладки.
 *
 * Спрашиваем только там, где есть что терять: молчаливый вопрос на каждый
 * прогон приучает жать «да» не читая — и в тот раз, когда он важен, его
 * прожмут так же.
 */
export function leaveChoice(state: RunLeaving): RunLeaveChoice {
  return state === 'wrote' ? 'ask' : 'stop';
}

/**
 * Что сказать человеку при закрытии. `null` — спрашивать нечего.
 *
 * Текст говорит последствие, а не действие: «уже изменил файлов: 3» — это то,
 * что надо знать, чтобы выбрать; «отменить прогон?» не говорит ничего.
 */
export function leaveQuestion(state: RunLeaving, files: number, steps: number): string | null {
  if (leaveChoice(state) !== 'ask') return null;
  const what = files > 0 ? `уже изменил файлов: ${files}` : 'уже сделал несколько шагов';
  const stepsText = files > 0 && steps > 0 ? ` за ${steps === 1 ? 'один шаг' : `${steps} шагов`}` : '';
  return `Агент ${what}${stepsText}. Если бросить — эта работа останется, а ответа вы не увидите.`;
}
