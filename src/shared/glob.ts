/**
 * Маска файлов в регулярное выражение. Вынесено из workspace.ts: одна и та же
 * логика нужна и поиску по содержимому, и find_files, и агенту, а проверить
 * её правила проще отдельной чистой функцией, чем через файловый обход.
 *
 * Поддерживаются знаки, которых достаточно для «найди файлы такого вида»:
 * - двойная звёздочка — любая глубина, включая ноль каталогов;
 * - одна звёздочка — в пределах одного сегмента пути;
 * - вопросительный знак — ровно один символ, но не слэш: привычная маска
 *   `router.?s` и «любой символ» без риска перейти на другой уровень.
 *
 * Фигурные скобки (`{a,b}`) намеренно не поддерживаются: они экранируются как
 * обычные символы, чтобы маска неожиданно не толковалась как регулярное
 * выражение. Отдельно различаются «двойная звёздочка со слэшем»
 * (любое число каталогов на пути) и одиночная двойная звёздочка (всё, включая
 * сами файлы, — так маска вида «папка/двойная звёздочка» находит и файлы в ней).
 */
export function globToRegExp(glob: string): RegExp {
  const escaped = glob.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  const body = escaped
    .replace(/\*\*\//g, '\u0000') // двойная звёздочка со слэшем: любое число каталогов
    .replace(/\*\*/g, '\u0001') // одиночная двойная звёздочка: что угодно, включая файлы
    .replace(/\*/g, '[^/]*') // одна звёздочка: в пределах сегмента
    .replace(/\?/g, '[^/]') // один символ, но не слэш: уровень пути не переходим
    .replace(/\u0000/g, '(?:[^/]*/)*')
    .replace(/\u0001/g, '.*');
  return new RegExp(`^${body}$`);
}

/**
 * Маска из НАСТРОЕК (значки дерева, исключённые файлы) в регулярное выражение.
 *
 * Отличие от `globToRegExp` вдвух: без учёта регистра (на Windows регистр в именах
 * файлов ни о чём не говорит) и без особого случая «двойная звёздочка со слэшем»:
 * такую маску сверяют и с именем, и с путём по отдельности.
 *
 * Общий модуль, потому что эту сборку повторяли два места — дерево (`ui/explorer.ts`)
 * и значки (`icon-badges.ts`), причём на каждом кадре.
 */
export function maskToRegExp(pattern: string): RegExp {
  const source = pattern
    .trim()
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\*\*/g, '\u0001')
    .replace(/\*/g, '[^/]*')
    .replace(/\?/g, '[^/]')
    .replace(/\u0001/g, '.*');
  return new RegExp(`^(?:${source})$`, 'i');
}
