/**
 * Маска файлов в регулярное выражение. Вынесено из workspace.ts: одна и та же
 * логика нужна и поиску по содержимому, и find_files, и агенту, а проверить
 * её правила проще отдельной чистой функцией, чем через файловый обход.
 *
 * Поддерживаются ровно два знака, которых достаточно для «найди файлы такого вида»:
 * - двойная звёздочка — любая глубина, включая ноль каталогов;
 * - одна звёздочка — в пределах одного сегмента пути.
 *
 * Вопросительный знак и фигурные скобки намеренно не поддерживаются: они
 * экранируются как обычные символы, чтобы маска неожиданно не толковалась как
 * регулярное выражение. Отдельно различаются «двойная звёздочка со слэшем»
 * (любое число каталогов на пути) и одиночная двойная звёздочка (всё, включая
 * сами файлы, — так маска вида «папка/двойная звёздочка» находит и файлы в ней).
 */
export function globToRegExp(glob: string): RegExp {
  const escaped = glob.replace(/[.+^${}()|[\]\\?]/g, '\\$&');
  const body = escaped
    .replace(/\*\*\//g, '\u0000') // двойная звёздочка со слэшем: любое число каталогов
    .replace(/\*\*/g, '\u0001') // одиночная двойная звёздочка: что угодно, включая файлы
    .replace(/\*/g, '[^/]*') // одна звёздочка: в пределах сегмента
    .replace(/\u0000/g, '(?:[^/]*/)*')
    .replace(/\u0001/g, '.*');
  return new RegExp(`^${body}$`);
}
