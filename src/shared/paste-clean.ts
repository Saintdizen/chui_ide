/**
 * Чистка вставленного текста — чтобы чужое форматирование не осело в файле.
 *
 * Ctrl+Shift+V в этой сборке отдельной команды не требует: вставка УЖЕ берёт
 * только `text/plain` (editor-input.ts, `clipboardData.getData('text/plain')`),
 * и HTML из буфера не приходит вовсе. Но «форматирование» приезжает и внутри
 * самого текста — невидимыми знаками. Их и чистим: иначе в файл попадают
 * неразрывный пробел и мягкий перенос, которые глаза не видят, а компилятор —
 * очень: строка перестаёт совпадать с искомой, регулярка не находится,
 * диф показывает «ничего не изменилось».
 */

/** Невидимые знаки, которые выдают себя за обычные. */
const INVISIBLE: ReadonlyArray<[RegExp, string]> = [
  // Неразрывный и узкий неразрывный пробел — самый частый гость из веба и Word.
  [/[\u00a0\u2007]/g, ' '],
  // Мягкий перенос (soft hyphen): виден только при разрыве строки.
  [/\u00ad/g, ''],
  // Знаки нулевой ширины и невидимая метка порядка байтов.
  //
  // ‍ (zero width joiner) сюда НЕ входит: он склеивает знаки в один.
  // Убрав его, мы развалили бы составные эмодзи — «семья» из одного знака
  // превратилась бы в пятерых. Стереть невидимое и стереть значимое — не одно и то же.
  [/[\u200b\u200c\u2060\ufeff]/g, ''],
  // Разделители строк из PDF и Word: \u2028/\u2029 редактор не считает строкой.
  [/[\u2028]/g, '\n'],
  [/\u2029/g, '\n\n'],
];

/**
 * Привести вставленный текст к тому, что редактор умеет показывать.
 *
 * Границы строк в буфере — `\r\n` на Windows и один `\r` на старом Mac. Редактор
 * работает с `\n`; оставить `\r` значит получить невидимый знак в конце каждой
 * строки — тот же вред, что от NBSP, только заметнее на глаз.
 *
 * Табуляции НЕ трогаем: они значат дело, и «без форматирования» не про них.
 */
export function cleanPastedText(text: string): string {
  let result = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  for (const [pattern, replacement] of INVISIBLE) result = result.replace(pattern, replacement);
  return result;
}
