/**
 * Сообщение коммита по diff (AI): «что мы вообще меняли» — модели, обратно — текст.
 *
 * Здесь только чистая часть затеи: нарезка diff по размеру, сборка промпта и
 * очистка ответа. Сам запрос к провайдеру живёт в main, кнопка — в renderer,
 * поэтому логику можно проверить тестами без сети и без окна.
 *
 * Почему не через чат: сообщение коммита — это не беседа и не требует истории,
 * инструментов и карты проекта. Один запрос — один ответ, как у inline-подсказок
 * (`shared/inline-ai.ts`); так оно и дешевле, и предсказуемее.
 */

/** Длина темы коммита: дальше строка обрезается в `git log --oneline` и на GitHub. */
export const COMMIT_SUBJECT_LIMIT = 72;
/** Потолок diff, который отдаём модели: больше — дорого и без пользы для темы. */
export const COMMIT_DIFF_MAX_CHARS = 8000;
/** Потолок ответа: тема и, если нужно, короткий список пунктов. */
export const COMMIT_MAX_TOKENS = 400;
/** Жёсткий предел длины ответа: защита от модели, которая не послушалась `maxTokens`. */
export const COMMIT_MAX_CHARS = 2000;

/**
 * Правило для модели. Главное здесь — то, чего НЕ должно быть в ответе: пояснений,
 * ограждений, обращения к человеку и кавычек. Сообщение идёт прямо в `git commit -m`,
 * и всё лишнее придётся стирать руками.
 */
export const COMMIT_SYSTEM_PROMPT = [
  'Ты пишешь сообщение коммита по diff. Отвечай по-русски, как принято в этом репозитории:',
  'короткая тема в повелительном наклонении, без точки в конце (например «Редактор: свёртка блоков»).',
  `Тема — не длиннее ${COMMIT_SUBJECT_LIMIT} символов и по существу: что изменилось, а не «правки в файлах».`,
  'Если правок несколько и они разной природы — после пустой строки добавь 2–4 пункта списком',
  'с «- », каждый одной строкой. Если правка одна и мелкая — только тема, без тела.',
  'Верни ТОЛЬКО текст сообщения: без пояснений, без markdown-ограждений, без кавычек вокруг,',
  'без строки «Сообщение коммита:». Не пересказывай построчно весь diff.',
].join('\n');

export interface CommitPromptParts {
  /** Унифицированный diff (уже обрезанный по `COMMIT_DIFF_MAX_CHARS`). */
  diff: string;
  /** Правки проиндексированы — в коммит пойдут они, а не всё рабочее дерево. */
  staged: boolean;
  /** Текущая ветка: помогает понять контекст («это ветка про свёртку»). */
  branch?: string | null;
  /** Новые файлы: их содержимого в diff нет, но названия о правке говорят. */
  untracked?: readonly string[];
}

/**
 * Обрезать diff до потолка. Режем по строкам и стараемся не рвать пополам строку
 * `@@ ... @@` с заголовком блока: оборванный diff модель читает хуже целого куска.
 * Признак обрезки остаётся в тексте — по нему видно, что картина неполная.
 */
export function truncateDiff(
  diff: string,
  maxChars: number = COMMIT_DIFF_MAX_CHARS,
): { text: string; truncated: boolean } {
  const limit = Math.max(maxChars, 1);
  if (diff.length <= limit) return { text: diff, truncated: false };

  const cut = diff.slice(0, limit);
  const at = cut.lastIndexOf('\n');
  const text = at > 0 ? cut.slice(0, at) : cut;
  return { text: `${text}\n… (diff обрезан: показана только часть правок)`, truncated: true };
}

/** Промпт с diff: что коммитим, где и в каком объёме. */
export function buildCommitPrompt(parts: CommitPromptParts): string {
  const head: string[] = [];
  head.push(parts.staged ? 'Коммитятся проиндексированные правки (git diff --cached).' : 'Правки ещё не в индексе.');
  if (parts.branch) head.push(`Текущая ветка: ${parts.branch}.`);
  if (parts.untracked && parts.untracked.length > 0) {
    head.push(`Новые файлы (в diff не видны): ${parts.untracked.slice(0, 20).join(', ')}.`);
  }

  return `${head.join('\n')}\n\n\`\`\`diff\n${parts.diff}\n\`\`\``;
}

/**
 * Очистить ответ модели. Модели любят добавлять ограждение, кавычки и подпись
 * «Сообщение коммита:» — всё это в `git commit -m` лишнее. Тело сообщения
 * (после пустой строки) сохраняем как есть: там осмысленные переводы строк.
 */
export function cleanCommitMessage(raw: string): string {
  let text = raw.replace(/\r\n?/g, '\n').trim();

  // Ограждение: ```…``` целиком или одна незакрытая строка.
  const fence = /^```[^\n]*\n([\s\S]*?)\n?```$/.exec(text);
  if (fence) text = (fence[1] ?? '').trim();
  else
    text = text
      .replace(/^```[^\n]*\n/, '')
      .replace(/\n?```$/, '')
      .trim();

  // Подпись перед сообщением: «Сообщение коммита: …». Снимаем только в начале строки,
  // иначе пострадало бы само упоминание этих слов в теле.
  text = text.replace(/^(?:сообщение(?:\s+коммита)?|commit message)\s*[::—-]\s*/i, '');

  // Кавычки вокруг всего сообщения — отдаём текст без них.
  const quoted = /^(["'«„])([\s\S]*)(["'»“])$/.exec(text);
  if (quoted) text = (quoted[2] ?? '').trim();

  // Хвостовые пробелы и лишние пустые строки — не часть сообщения.
  text = text
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/\n+$/, '');

  const [subject, ...rest] = text.split('\n');
  // Точка в конце темы — привычка, от которой страдает git log: заголовок и так
  // читается как фраза. Убираем ровно одну, тело не трогаем.
  const head = (subject ?? '').replace(/\.$/, '');
  return [head, ...rest].join('\n').trim();
}

/** Пустое ли сообщение вышло после очистки (тогда показывать нечего). */
export function isEmptyCommitMessage(message: string): boolean {
  return message.trim().length === 0;
}
