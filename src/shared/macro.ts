/**
 * Макрос в сессии проекта: предел длины и сырые шаги из файла.
 *
 * Сами шаги описывает редактор (`renderer/editor/input/macro.ts`) — там же их разбор
 * и повтор. Здесь только то, что нужно хранилищу сессии: сколько шагов пускать и как
 * принять список из файла, который мог править человек.
 */

/** Предел длины макроса: зажатая клавиша не должна растить запись бесконечно. */
export const MAX_MACRO_STEPS = 2000;

/**
 * Сырые шаги макроса из сессии: только массив, обрезанный по пределу. Читать форму
 * шага — дело редактора: сессия не знает ни видов движений, ни команд.
 */
export function rawMacroSteps(raw: unknown): unknown[] {
  return Array.isArray(raw) ? raw.slice(0, MAX_MACRO_STEPS) : [];
}
