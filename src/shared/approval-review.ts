/**
 * Проверка подтверждений моделью: второе мнение перед карточкой в ленте.
 *
 * Обычный режим прав спрашивает обо всём. Это честно, но дорого человеку: агент
 * за один ответ запускает десяток безобидных команд (`ls`, `git status`, `npm run
 * lint`), и каждый раз нужно нажать «Разрешить» — на третьем вопросе начинают
 * нажимать не читая, и тогда подтверждение перестаёт что-либо значить.
 *
 * Поэтому между «спросить человека» и «разрешить молча» появляется третий
 * вариант: короткий запрос к дешёвой модели — «что делает эта команда, есть ли в
 * ней запись, удаление или выход в сеть». Ответ разбирается здесь, в чистом
 * модуле, по одной строгой форме.
 *
 * Главное правило — отказ в сторону вопроса. Всё непонятное (пустой ответ, ответ
 * не по форме, оба решения, ошибка сети, таймаут) означает «спросить человека».
 * Цена лишнего вопроса — одно нажатие; цена неверного «разрешаю» — выполненная
 * команда, которую отменить нечем.
 *
 * Необратимые команды не проверяются вовсе: `rm -rf`, `sudo`, `git push --force`
 * идут к человеку всегда (список — `isDangerousCommand` в `agent-tools.ts`).
 * Модель тут не судья, даже если она уверена.
 *
 * Модуль чистый: ни сети, ни настроек, ни Electron. Кто спрашивает модель —
 * `AiService.reviewCommand`, кто решает спрашивать — `registerIpc`.
 */

/** Решение проверяющего. `ask` — не «запретить», а «пусть решит человек». */
export type ReviewDecision = 'allow' | 'ask';

export interface ReviewVerdict {
  decision: ReviewDecision;
  /** Одна строка для человека: попадает в ленту или в подсказку карточки. */
  reason: string;
}

/**
 * Слова, которыми модель отвечает. Английские и заглавные намеренно: их не
 * спутать с обычным текстом ответа, и разбор не зависит от языка объяснения.
 */
const ALLOW = 'ALLOW';
const ASK = 'ASK';

/** Потолок причины: это подпись к решению, а не эссе. */
export const MAX_REVIEW_REASON = 240;
/** Длиннее — уже не команда, а спрятанный скрипт; такую не разбираем, а спрашиваем. */
export const MAX_REVIEW_COMMAND = 2000;

/**
 * Сколько ждём проверяющего. Дольше — и человек уже успел бы нажать сам, а шаг
 * агента стоит на месте: проверка обязана быть дешевле своего отсутствия.
 */
export const REVIEW_TIMEOUT_MS = 8000;

/** Системная часть запроса: роль, форма ответа и склонность спросить лишний раз. */
export const REVIEW_SYSTEM_PROMPT = [
  'Ты — проверяющий безопасности в редакторе кода. Тебе дают команду, которую агент',
  'хочет выполнить в проекте пользователя. Реши, можно ли выполнить её без спроса.',
  '',
  'Отвечай РОВНО одной строкой и больше ничего не пиши:',
  `  ${ALLOW}: <короткая причина по-русски>`,
  '  — если команда только читает: просмотр, поиск, git status/diff/log, сборка, тесты, линтер;',
  `  ${ASK}: <короткая причина по-русски>`,
  '  — если команда меняет файлы или систему, ходит в сеть, ставит или удаляет пакеты,',
  '    трогает git-историю, запускает что-то долгое в фоне или её смысл тебе непонятен.',
  '',
  'Сомневаешься — отвечай ASK. Проверить лишний раз дешевле, чем отменить сделанное.',
  'Причина — одна строка, без вступлений и без Markdown.',
].join('\n');

/**
 * Пользовательская часть: команда и где она выполняется. Обрезаем по потолку —
 * такую команду всё равно не разобрать, и она уйдёт человеку.
 */
export function buildReviewPrompt(command: string, cwd?: string): string {
  const text = command.trim().slice(0, MAX_REVIEW_COMMAND);
  return cwd ? `Проект: ${cwd}\n\nКоманда:\n${text}` : `Команда:\n${text}`;
}

/** Разбор ответа проверяющего. Непонятное — `ask`. */
export function parseReviewVerdict(raw: string): ReviewVerdict {
  const text = raw.trim();
  if (!text) return { decision: 'ask', reason: 'проверяющий промолчал' };

  // Оба маркера в ответе — модель не определилась: решает человек.
  const hasAllow = new RegExp(`(^|\\n)\\s*${ALLOW}\\b`, 'i').test(text);
  const hasAsk = new RegExp(`(^|\\n)\\s*${ASK}\\b`, 'i').test(text);
  if (hasAllow && hasAsk) return { decision: 'ask', reason: 'проверяющий назвал два решения' };

  // Решение — только в НАЧАЛЕ ответа: «не ALLOW, потому что…» не должно читаться
  // как разрешение.
  const head = new RegExp(`^\\s*(${ALLOW}|${ASK})\\b\\s*[:\\-—]?\\s*([\\s\\S]*)$`, 'i').exec(text);
  if (!head) return { decision: 'ask', reason: 'проверяющий ответил не по форме' };

  const decision: ReviewDecision = head[1]!.toUpperCase() === ALLOW ? 'allow' : 'ask';
  const reason = (head[2] ?? '').replace(/\s+/g, ' ').trim().slice(0, MAX_REVIEW_REASON);
  return { decision, reason: reason || 'без пояснения' };
}

/**
 * Стоит ли вообще спрашивать модель об этой команде.
 *
 * Не стоит в трёх случаях: проверка выключена, команда необратима (её решает
 * человек) и команда слишком длинная (её не разобрать по одной строке).
 */
export function shouldReview(command: string, options: { enabled: boolean; dangerous: boolean }): boolean {
  if (!options.enabled) return false;
  if (options.dangerous) return false;
  const text = command.trim();
  if (!text) return false;
  if (text.length > MAX_REVIEW_COMMAND) return false;
  return true;
}
