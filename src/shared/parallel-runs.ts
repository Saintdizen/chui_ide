/**
 * Два прогона в одном каталоге: что сказать человеку.
 *
 * Параллельные задачи — это две правки в одних и тех же файлах. Тишина тут
 * хуже всего: обе стороны считают файл своим, и чужое изменение выглядит как
 * поломка. Пока изоляции нет, единственное честное поведение — сказать об этом
 * в момент старта и сказать, что с этим делать.
 */
export function parallelRunNotice(running: number): string | null {
  if (running < 2) return null;
  return (
    'Две задачи идут в одном каталоге: их правки лягут в одни и те же файлы. ' +
    'Чтобы не мешали — уведите задачу в отдельную ветку кнопкой в шапке чата.'
  );
}
