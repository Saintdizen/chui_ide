import { describe, expect, it } from 'vitest';
import { computeWindow } from '../src/renderer/core/tree-window';

/**
 * Окно рисуемых строк дерева. Промах на единицу означал бы дырку в списке или
 * лишнюю строку на экране, поэтому границы проверяем отдельно, включая крайние
 * случаи: пустой список, высота в ноль, прокрутка за конец.
 */
describe('computeWindow', () => {
  it('в начале списка рисует с нуля до видимой части плюс запас', () => {
    // 240px видно, строка 24px → видно 10 строк; запас 2 с каждой стороны.
    expect(computeWindow(100, 0, 240, 24, 2)).toEqual({ first: 0, last: 12 });
  });

  it('в середине окно сдвигается на номер первой видимой строки минус запас', () => {
    // Прокрутка 2400 → строка 100; запас 2 → первая 98; видно ещё 10 → 110 + 2.
    expect(computeWindow(1000, 2400, 240, 24, 2)).toEqual({ first: 98, last: 112 });
  });

  it('в конце список обрезается по последней строке', () => {
    expect(computeWindow(50, 1200, 240, 24, 2).last).toBe(50);
  });

  it('пустой список — пустое окно', () => {
    expect(computeWindow(0, 0, 240, 24)).toEqual({ first: 0, last: 0 });
  });

  it('высота строки в ноль не делит на ноль', () => {
    expect(computeWindow(10, 100, 240, 0)).toEqual({ first: 0, last: 0 });
  });

  it('отрицательная прокрутка считается началом списка', () => {
    expect(computeWindow(100, -50, 240, 24, 2).first).toBe(0);
  });

  it('номер строки не уходит ниже нуля даже с большим запасом', () => {
    const window = computeWindow(100, 10, 24, 24, 8);
    expect(window.first).toBe(0);
  });
});
