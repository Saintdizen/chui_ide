import { describe, expect, it } from 'vitest';
import type { CommandDescriptor } from '../src/renderer/core/commands';
import { rankCommands } from '../src/renderer/core/palette-rank';

const command = (id: string, title: string, extra: Partial<CommandDescriptor> = {}): CommandDescriptor =>
  ({ id, title, category: 'Вид', ...extra }) as CommandDescriptor;

const registry: CommandDescriptor[] = [
  command('view.collapseAll', 'Свернуть всё'),
  command('view.collapseToLevel', 'Свернуть всё до уровня'),
  command('view.expandAll', 'Развернуть всё'),
  command('dock.toggle', 'Скрыть панель', { keywords: ['свернуть', 'боковая'] }),
  command('editor.wordWrap', 'Перенос строк'),
];

/** Порядок заголовков — то, что человек видит в списке. */
const titles = (query: string, recent: string[] = []): string[] =>
  (rankCommands(registry, query, recent) ?? []).map((item) => item.title);

describe('rankCommands', () => {
  it('находит команду, когда слова в другом порядке', () => {
    // Главный дефект: было `haystack.includes(query)` — «все свернуть» не
    // находило «Свернуть всё». Палитра нужна сильнее всего именно тогда,
    // когда точной формы слова в голове нет.
    expect(titles('все свернуть')).toContain('Свернуть всё');
  });

  it('игнорирует ё/е', () => {
    expect(titles('свернуть все')).toContain('Свернуть всё');
  });

  it('совпадение с начала названия идёт раньше прочих', () => {
    // «Свернуть всё» (начало) против «Скрыть панель», у которой
    // «свернуть» только в ключевых словах.
    expect(titles('свернуть')[0]).toBe('Свернуть всё');
  });

  it('точное название — первым', () => {
    expect(titles('свернуть всё')[0]).toBe('Свернуть всё');
  });

  it('при равном совпадении выше та, что запускали недавно', () => {
    // «Свернуть всё» и «Свернуть всё до уровня» ранжируются одинаково:
    // решает история, а не порядок регистрации (то есть случай).
    // Тест был неверен, а не код: «Свернуть всё» совпадает ЦЕЛИКОМ (ранг 0),
    // «…до уровня» — только началом (ранг 1). Ранги разные, и история между
    // ними решать не должна: точное название человека — это и есть его ответ.
    // Равный ранг — это две команды, начинающиеся одинаково (ниже).
    expect(titles('свернуть всё', ['view.collapseToLevel'])[0]).toBe('Свернуть всё');
  });

  it('при равном совпадении выше та, что запускали недавно (одинаковое начало)', () => {
    // Обе — ранг 1 (начинаются с «свернуть всё»), но ни одна не совпадает целиком.
    // Здесь решает история: запускали «до уровня» — она и выше.
    expect(titles('свернуть всё до', ['view.collapseToLevel', 'view.collapseAll'])[0]).toBe('Свернуть всё до уровня');
  });

  it('история не пробивает себе дорогу выше лучшего совпадения', () => {
    // Иначе привычная команда хоронила бы точное совпадение — одна из
    // причин, по которой в палитре брали «что попало».
    expect(titles('перенос', ['view.collapseAll'])[0]).toBe('Перенос строк');
  });

  it('без запроса — null: порядок задаёт история, а не поиск', () => {
    // `null`, а не `[]`: пустой список читался бы как «ничего не нашлось»,
    // и палитра показала бы человеку пустоту вместо привычных команд.
    expect(rankCommands(registry, '   ')).toBeNull();
  });

  it('не нашлось — пусто, а не весь список', () => {
    expect(titles('такого нет')).toEqual([]);
  });

  it('потолок соблюдается', () => {
    expect(rankCommands(registry, 'свернуть', [], 1)).toHaveLength(1);
  });

  it('ищет по ключевым словам и id', () => {
    expect(titles('боковая')).toEqual(['Скрыть панель']);
    expect(titles('wordWrap')).toEqual(['Перенос строк']);
  });
});
