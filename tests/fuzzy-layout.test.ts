import { describe, expect, it } from 'vitest';
import { looseScore, matchScore } from '../src/shared/fuzzy';

/**
 * Набрано не в той раскладке — самый частый промах в поиске: человек знает
 * имя точно, но забыл переключить язык. `ghbdtn` вместо `привет`, `djn` вместо
 * `вот`. Подсказка обязана это простить; иначе поиск молчит там, где человек
 * прав.
 *
 * Прощение односторонее и на один знак: одна замена по таблице раскладки.
 * Заглавная по-прежнему требует заглавной: раскладка не отменяет регистр.
 */

describe('раскладка клавиатуры', () => {
  it('латиница находит кириллическое имя', () => {
    // `ghbdtn` на английской — это `привет` на русской.
    expect(matchScore('привет', 'ghbdtn')).not.toBeNull();
  });

  it('беглая раскладка тоже прощается', () => {
    // `htlfrnjhs` — это `редакторы`; в нечётком режиме тоже должно найтись.
    expect(looseScore('редакторы', 'htlfrnjhs')).toBeGreaterThan(Number.NEGATIVE_INFINITY);
  });

  it('своя раскладка не пострадала', () => {
    expect(matchScore('text', 'text')).not.toBeNull();
    expect(matchScore('текст', 'текст')).not.toBeNull();
  });

  it('чужое слово всё ещё не совпадает', () => {
    expect(matchScore('текст', 'zzzzz')).toBeNull();
  });

  it('заглавная по-прежнему строга', () => {
    // Прощение по раскладке не отменяет регистр: `Ф` ищет именно заглавную.
    expect(matchScore('abc', 'Ф')).toBeNull();
  });
});
